def set_paragraph_text(paragraph, text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def replace_everywhere(doc: Document, old: str, new: str) -> None:
    for paragraph in doc.paragraphs:
        if old in paragraph.text:
            set_paragraph_text(paragraph, paragraph.text.replace(old, new))
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    if old in paragraph.text:
                        set_paragraph_text(paragraph, paragraph.text.replace(old, new))


def find_heading(doc: Document, text: str):
    for i, paragraph in enumerate(doc.paragraphs):
        if paragraph.text.strip() == text:
            return i, paragraph
    raise ValueError(f"heading not found: {text}")


def replace_after_heading(doc: Document, heading: str, paragraphs: list[str]) -> None:
    start, _ = find_heading(doc, heading)
    body_indexes = []
    for i in range(start + 1, len(doc.paragraphs)):
        p = doc.paragraphs[i]
        if p.style.name.startswith("Report Heading"):
            break
        if p.style.name == "Report Body" and p.text.strip():
            body_indexes.append(i)
    if len(body_indexes) < len(paragraphs):
        raise ValueError(f"not enough body paragraphs after {heading}: {len(body_indexes)}")
    for idx, text in zip(body_indexes, paragraphs):
        set_paragraph_text(doc.paragraphs[idx], text)


