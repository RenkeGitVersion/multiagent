def insert_paragraph_before(paragraph, text="", style=None):
    new_p = OxmlElement("w:p")
    paragraph._p.addprevious(new_p)
    new_para = paragraph.__class__(new_p, paragraph._parent)
    if style:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


def add_para(anchor, text="", style="Report Body", align=None):
    p = insert_paragraph_before(anchor, "", style)
    if text:
        p.add_run(text)
    if align is not None:
        p.alignment = align
    return p


def add_image(anchor, path: Path, width_inches=6.65):
    p = insert_paragraph_before(anchor, "", "Report Body")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(path), width=Inches(width_inches))
    return p


def add_table(anchor, rows: list[list[str]], widths: list[float] | None = None):
    tbl = anchor._parent.add_table(rows=len(rows), cols=len(rows[0]), width=Inches(6.5))
    anchor._p.addprevious(tbl._tbl)
    tbl.style = "Table Grid"
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            cell = tbl.cell(r, c)
            cell.text = text
            if widths:
                cell.width = Inches(widths[c])
            for para in cell.paragraphs:
                para.style = "Report Body"
                if r == 0:
                    for run in para.runs:
                        run.bold = True
    add_para(anchor, "", "Report Body")
    return tbl


